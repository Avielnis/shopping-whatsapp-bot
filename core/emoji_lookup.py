_DEFAULT_EMOJI = "🛒"

_EMOJI_BY_KEYWORD = {kw: emoji for _, items in _CATEGORIES for kw, emoji in items.items()}
_CATEGORY_BY_KEYWORD = {kw: i for i, (_, items) in enumerate(_CATEGORIES) for kw in items}
_MULTI_WORD = sorted((kw for kw in _EMOJI_BY_KEYWORD if " " in kw), key=len, reverse=True)
_LONGEST_FIRST = sorted(_EMOJI_BY_KEYWORD, key=len, reverse=True)


def _match(name: str) -> str | None:
    # multi-word first ("תפוח אדמה" is a potato, not an apple), then whole words,
    # then substrings (catches plurals/prefixes like "ועגבניות")
    for kw in _MULTI_WORD:
        if kw in name:
            return kw
    for word in name.split():
        if word in _EMOJI_BY_KEYWORD:
            return word
    for kw in _LONGEST_FIRST:
        if kw in name:
            return kw
    return None


def emoji_for(name: str) -> str:
    kw = _match(name)
    return _EMOJI_BY_KEYWORD[kw] if kw else _DEFAULT_EMOJI


def category_index(name: str) -> int:
    """Position of the item's category in _CATEGORIES; unknown items go last."""
    kw = _match(name)
    return _CATEGORY_BY_KEYWORD[kw] if kw else len(_CATEGORIES)


def label(name: str) -> str:
    return f"{emoji_for(name)} {name}"
